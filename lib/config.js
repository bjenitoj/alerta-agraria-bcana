export function sourceById(id) {
  return SOURCES.find((source) => source.id === id) || null;
}

export function publicSourceView(reports = {}, collectedAt = null) {
  return {
    groups: SOURCE_GROUPS,
    methodology: METHODOLOGY,
    about: ABOUT,
    collectedAt,
    sources: SOURCES.map((source) => {
      const report = reports[source.id] || null;
      let status = "pendiente";
      if (source.kind === "nota") status = "sin_canal";
      else if (!source.enabled) status = "preparada";
      else if (report?.ok) status = "ok";
      else if (report && report.ok === false) status = "error";
      return {
        id: source.id,
        name: source.name,
        organism: source.organism,
        group: source.group,
        url: source.url,
        covers: source.covers,
        enabled: Boolean(source.enabled),
        sectors: source.sectors,
        status,
        lastOkAt: report?.lastOkAt || null,
        count: report?.ok && Number.isFinite(report.count) ? report.count : null,
        note: report?.note || null,
        error: report && report.ok === false ? report.error || null : null,
        reuse: source.reuse || null,
      };
    }),
  };
}
